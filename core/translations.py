def notif_text(user, uz, ru='', en=''):
    """Return notification string in user's preferred_language."""
    lang = getattr(user, 'preferred_language', 'uz') or 'uz'
    if lang == 'ru':
        return ru or uz
    if lang == 'en':
        return en or uz
    return uz
